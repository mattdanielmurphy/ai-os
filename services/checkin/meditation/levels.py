"""Mindfulness levels: writes scripts/level-<n>.txt, one per step of the page's difficulty slider.

  python3 levels.py            then: for n in 1..8: python3 build.py scripts/level-<n>.txt

Each track opens with three guided slow breaths that flow into the sit, so one press covers both (Matt, 10-30).
The page's circle follows the breaths from BREATHS and LEAD below. Each level then sets the sit's length, how often
the bell rings, and how much the voice says. No bell in the sit's first minute, when the voice talks a lot, so
level 1 has none. Mindfulness, not a breathing exercise: after the transition the breath is left alone and never
directed again (Matt, 10-27).
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEAD = """# voice: marian
# speed: 1.0
# music: ~/projects/claude-ambient/out/loop-breath-20m.flac
# drone: ~/projects/claude-ambient/out/drone-d-organ-21m.flac
# bell: ~/projects/ai-os/services/checkin/meditation/bell-tingsha.flac
# Generated by levels.py; edit there, not here.
"""

BREATHS = {"start": 9, "in": 4, "out": 6, "count": 3}  # s; the page's circle reads these
LEAD = 48          # s into the track where the sit starts, after the breaths and the transition

# level: (minutes, seconds between bells, how many mid-sit reminders)
LEVELS = {1: (1, 15, 0), 2: (2, 20, 0), 3: (3, 30, 1), 4: (5, 45, 3),
          5: (7, 60, 3), 6: (10, 90, 3), 7: (15, 120, 2), 8: (20, 180, 2)}
WORDS = {2: "two minutes", 3: "three minutes", 5: "five minutes", 7: "seven minutes",
         10: "ten minutes", 15: "fifteen minutes", 20: "twenty minutes"}

# Said during the sit, in this order; a level uses the first n.
REMINDERS = [
    "Your mind will wander. That's fine. Noticing that it wandered is the whole practice.",
    "If you're lost in a thought, no problem. Let it go, and feel the next breath.",
    "There's nothing to get right. Just this breath, and then the next one.",
]


def opening():
    """The three breaths and the transition, at fixed times so the page's circle stays in step."""
    out = ["[pause 2]", "Three slow breaths. Follow the voice."]
    for i in range(BREATHS["count"]):
        t = BREATHS["start"] + i * (BREATHS["in"] + BREATHS["out"])
        out += [f"[at {t}]", "Breathe in.", f"[at {t + BREATHS['in']}]", "And out."]
    t = BREATHS["start"] + BREATHS["count"] * (BREATHS["in"] + BREATHS["out"])
    return out + [f"[at {t}]", "Okay. Now let your breathing return to normal, and just watch it.", f"[at {LEAD}]"]


def script(level):
    minutes, every, n = LEVELS[level]
    head = HEAD + f"# minutes: {minutes + LEAD / 60:.3f}\n# bell_every: {every}" + ("\n# fade_out: 5" if minutes < 5 else "")
    out = [head] + opening()
    if minutes == 1:  # one minute leaves room for only a few words, and no bell
        return "\n".join(out + ["Just one minute. Let your eyes stay closed.", "[fill]",
                                 "And open your eyes.", "[pause 2]"]) + "\n"
    out += [f"For the next {WORDS[minutes]}, there's nothing to do but notice.", "[pause 3]",
            "Rest your attention on the breath, wherever you feel it most.", f"[at {LEAD + 60 - 8}]",
            "When you hear this sound, come back to the breath.", "[pause 1]", "[bell]", "[fill]"]
    for line in REMINDERS[:n]:
        out += [line, "[fill]"]
    if minutes < 5:
        out += ["Let the practice go now. Notice how you feel. When you're ready, open your eyes.", "[pause 4]"]
    else:
        out += ["Let the practice go now. Notice how you feel.", "[pause 4]",
                "Feel your hands and feet. When you're ready, open your eyes.", "[pause 4]"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    for level in LEVELS:
        (HERE / "scripts" / f"level-{level}.txt").write_text(script(level))
        print(f"scripts/level-{level}.txt")
