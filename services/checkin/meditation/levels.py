"""Mindfulness levels: writes scripts/level-<n>.txt, one per step of the page's difficulty slider.

  python3 levels.py            then: for n in 1..8: python3 build.py scripts/level-<n>.txt

Each level sets the length, how often the bell rings, and how much the voice says during the sit.
Level 1 is one minute with lots of bells; level 8 is twenty minutes, mostly silence.
Mindfulness, not a breathing exercise: a couple of settling breaths at the start, then the breath is
left alone and never directed again (Matt, 10-27).
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEAD = """# voice: marian
# speed: 1.0
# music: ~/projects/claude-ambient/out/loop-breath-20m.flac
# drone: ~/projects/claude-ambient/out/drone-d-organ-21m.flac
# bell: ~/projects/claude-ambient/out/bell-mallets.flac
# Generated by levels.py; edit there, not here.
"""

# level: (minutes, seconds between bells, how many mid-sit reminders)
LEVELS = {1: (1, 15, 0), 2: (2, 20, 0), 3: (3, 30, 1), 4: (5, 45, 3),
          5: (7, 60, 3), 6: (10, 90, 3), 7: (15, 120, 2), 8: (20, 180, 2)}
WORDS = {2: "two minutes", 3: "three minutes", 5: "five minutes", 7: "seven minutes",
         10: "ten minutes", 15: "fifteen minutes", 20: "twenty minutes"}

# Said during the sit, in this order; a level uses the first n.
REMINDERS = [
    "Your mind will wander. That's fine. Noticing that it wandered is the whole practice.",
    "If you're lost in a thought, no problem. Let it go, and feel the next breath.",
    "There's nothing to get right. Just this breath, and then the next one.",
]


def script(level):
    minutes, every, n = LEVELS[level]
    out = [HEAD + f"# minutes: {minutes}\n# bell_every: {every}" + ("\n# fade_out: 5" if minutes < 5 else ""), "[pause 3]"]
    if minutes == 1:  # one minute leaves room for only a few words; most of it should be the sit itself
        return "\n".join(out + ["Just one minute. Close your eyes, and feel one breath.", "[pause 2]",
                                 "When you hear this sound, come back to the breath.", "[bell]", "[fill]",
                                 "And open your eyes.", "[pause 2]"]) + "\n"
    # A couple of settling breaths, then the breath is handed back and never directed again.
    out += [f"For the next {WORDS[minutes]}, there's nothing to do but notice. Let your eyes close.", "[pause 3]"]
    if minutes < 5:  # short sits: one settling breath, so most of the time is the sit itself
        out += ["Take one slow breath in... and let it go. Then let the breath do whatever it does on its own.",
                "[pause 4]"]
    else:
        out += ["Take one slow, deep breath in... and let it out slowly.", "[pause 5]",
                "One more. In... and a long breath out.", "[pause 5]",
                "Now let the breath go back to doing whatever it does on its own. You don't need to control it.",
                "[pause 5]"]
    out += ["Rest your attention on the breath, wherever you feel it most.", "[pause 2]",
            "When you hear this sound, take it as a reminder. If your mind has wandered, gently come back to the breath.",
            "[bell]", "[fill]"]
    for line in REMINDERS[:n]:
        out += [line, "[fill]"]
    if minutes < 5:
        out += ["Let the practice go now. Notice how you feel. When you're ready, open your eyes.", "[pause 4]"]
    else:
        out += ["Let the practice go now. Notice how you feel.", "[pause 4]",
                "Feel your hands and feet. When you're ready, open your eyes.", "[pause 4]"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    for level in LEVELS:
        (HERE / "scripts" / f"level-{level}.txt").write_text(script(level))
        print(f"scripts/level-{level}.txt")
